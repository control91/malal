"""
Generates the dotted map of Africa used by the « Vision » section.

Run: python scripts/build_africa_map.py  →  templates/public/includes/africa_map.html
The outline is a simplified hand-made polygon (no third-party map data).
"""

from pathlib import Path

AFRICA = [
    (-5.9, 35.8), (-1.9, 35.1), (3.0, 36.8), (10.2, 37.2), (11.1, 35.2), (10.1, 33.8), (11.5, 33.1), (15.2, 32.3),
    (18.5, 30.4), (20.1, 32.1), (23.0, 32.6), (25.2, 31.6), (29.9, 31.2), (32.3, 31.3), (32.6, 29.9), (33.6, 27.6),
    (35.5, 24.0), (37.2, 21.0), (37.4, 18.6), (38.6, 18.0), (39.7, 15.6), (41.7, 13.4), (43.3, 11.9), (44.5, 10.4),
    (51.2, 11.8), (51.0, 10.4), (49.8, 7.5), (48.5, 5.3), (45.3, 2.0), (42.5, -0.6), (40.9, -2.3), (39.7, -4.1),
    (39.3, -6.8), (39.5, -10.0), (40.5, -11.0), (40.6, -15.0), (36.9, -17.9), (34.8, -19.8), (35.5, -23.8),
    (32.6, -25.9), (32.9, -28.0), (31.0, -29.9), (28.0, -32.9), (25.6, -33.9), (20.0, -34.8), (18.4, -34.2),
    (18.0, -32.0), (16.5, -28.6), (15.2, -26.6), (14.5, -22.9), (11.8, -17.2), (13.4, -12.6), (13.2, -8.8),
    (12.3, -6.1), (11.9, -5.0), (8.8, -1.0), (9.6, 2.0), (9.7, 4.0), (8.5, 4.5), (6.0, 4.3), (3.4, 6.4), (1.2, 6.1),
    (-2.0, 4.8), (-4.0, 5.2), (-7.5, 4.4), (-10.8, 6.3), (-13.2, 8.5), (-13.7, 9.5), (-15.0, 10.8), (-16.7, 12.4),
    (-17.5, 14.7), (-16.5, 16.0), (-16.0, 18.0), (-17.0, 21.0), (-15.9, 23.7), (-13.0, 27.0), (-9.6, 30.4),
    (-9.2, 32.3), (-6.8, 34.0),
]
MADAGASCAR = [(49.3, -12.0), (50.5, -15.5), (49.5, -17.5), (47.2, -25.0), (45.2, -25.6), (43.6, -23.0), (43.3, -21.0), (44.4, -16.2), (46.5, -15.5), (48.0, -13.5)]
GUINEA = [(-15.0, 10.8), (-13.7, 12.6), (-11.4, 12.4), (-10.6, 11.9), (-9.0, 12.3), (-8.4, 11.4), (-7.8, 10.3), (-7.7, 8.6), (-8.3, 7.6), (-9.4, 7.6), (-10.2, 8.4), (-10.8, 9.3), (-12.4, 9.9), (-13.3, 9.2)]

HUB = ("Conakry", -13.7, 9.5)
WEST = [("Dakar", -17.4, 14.7), ("Bamako", -8.0, 12.6), ("Freetown", -13.2, 8.5), ("Abidjan", -4.0, 5.3), ("Accra", -0.2, 5.6),
        ("Lagos", 3.4, 6.5), ("Ouagadougou", -1.5, 12.4), ("Niamey", 2.1, 13.5), ("Nouakchott", -16.0, 18.1)]
CONTINENT = [("Casablanca", -7.6, 33.6), ("Le Caire", 31.2, 30.0), ("Addis-Abeba", 38.7, 9.0), ("Nairobi", 36.8, -1.3),
             ("Kigali", 30.1, -1.9), ("Kinshasa", 15.3, -4.3), ("Douala", 9.7, 4.05), ("Johannesburg", 28.0, -26.2)]

STEP, K, LON0, LAT0 = 1.7, 10, -19.5, 38.5


def inside(lon, lat, poly):
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def xy(lon, lat):
    return round((lon - LON0) * K, 1), round((LAT0 - lat) * K, 1)


def main():
    dots = []
    lat = LAT0 - 0.85
    while lat > -36:
        lon = LON0 + 0.85
        while lon < 52:
            if inside(lon, lat, AFRICA) or inside(lon, lat, MADAGASCAR):
                if inside(lon, lat, GUINEA):
                    region = "gn"
                elif lon <= 16 and 4 <= lat <= 24.5:
                    region = "wa"
                else:
                    region = "af"
                x, y = xy(lon, lat)
                dots.append(f'<circle class="{region}" cx="{x:g}" cy="{y:g}" r="3.4"/>')
            lon += STEP
        lat -= STEP
    # Guinea gets a denser sub-grid so the country reads clearly.
    lat = 12.6
    while lat > 7.4:
        lon = -14.9
        while lon < -7.6:
            if inside(lon, lat, GUINEA):
                x, y = xy(lon, lat)
                dots.append(f'<circle class="gn" cx="{x:g}" cy="{y:g}" r="2.6"/>')
            lon += 0.85
        lat -= 0.85

    hx, hy = xy(HUB[1], HUB[2])
    arcs, cities = [], []
    for phase, group in (("wa", WEST), ("af", CONTINENT)):
        for name, lon, lat in group:
            x, y = xy(lon, lat)
            mx, my = (hx + x) / 2, (hy + y) / 2 - abs(x - hx) * 0.18 - 12
            arcs.append(f'<path class="arc arc-{phase}" d="M{hx},{hy} Q{mx:.1f},{my:.1f} {x},{y}"/>')
            cities.append(f'<g class="city city-{phase}"><circle cx="{x}" cy="{y}" r="4.5"/><title>{name}</title></g>')

    width, height = round((52 - LON0) * K), round((LAT0 + 36) * K)
    svg = f'''{{# Generated by scripts/build_africa_map.py — do not edit by hand. #}}
<svg class="africa-map" viewBox="0 0 {width} {height}" role="img" aria-labelledby="africa-map-title" x-bind:data-phase="phase" data-phase="1">
  <title id="africa-map-title">Carte stylisée de l'Afrique : la Guinée, l'Afrique de l'Ouest puis le continent</title>
  <defs>
    <radialGradient id="hub-glow"><stop offset="0" stop-color="var(--color-accent)" stop-opacity=".55"/><stop offset="1" stop-color="var(--color-accent)" stop-opacity="0"/></radialGradient>
  </defs>
  <g class="dots">{"".join(dots)}</g>
  <g class="arcs" fill="none">{"".join(arcs)}</g>
  <g class="cities">{"".join(cities)}</g>
  <g class="hub"><circle cx="{hx}" cy="{hy}" r="46" fill="url(#hub-glow)" class="hub-glow"/><circle cx="{hx}" cy="{hy}" r="7" class="hub-core"/><circle cx="{hx}" cy="{hy}" r="7" class="hub-pulse"/><title>{HUB[0]}</title></g>
</svg>
'''
    out = Path(__file__).resolve().parent.parent / "templates/public/includes/africa_map.html"
    out.write_text(svg)
    print(f"{len(dots)} dots → {out}")


if __name__ == "__main__":
    main()
