// Builds resources/js/icons.js from the curated SVG icons in resources/icons/
// (Lucide, ISC licence + in-house brand glyphs). Run: npm run icons
// To add an icon: copy it from node_modules/lucide-static/icons/ into resources/icons/.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "resources/icons");
const icons = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(dir, file), "utf8").replace(/<!--[\s\S]*?-->/g, "");
  const open = svg.match(/<svg\b[^>]*>/)[0];
  const inner = svg.slice(svg.indexOf(open) + open.length).replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
  icons[file.replace(".svg", "")] = { body: inner, filled: open.includes('fill="currentColor"') };
}
writeFileSync(join(root, "resources/js/icons.js"), `// Generated by scripts/build-icons.mjs — do not edit.\nexport default ${JSON.stringify(icons)};\n`);
console.log(`${Object.keys(icons).length} icons → resources/js/icons.js`);
